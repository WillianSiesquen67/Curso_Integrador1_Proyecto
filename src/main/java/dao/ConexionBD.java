package dao;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public class ConexionBD {
    private static final String URL = "jdbc:h2:file:./data/control_acceso;AUTO_SERVER=TRUE";
    private static final String USER = "sa";
    private static final String PASSWORD = "";

    public static Connection obtenerConexion() throws SQLException {
        Connection con = DriverManager.getConnection(URL, USER, PASSWORD);
        inicializar(con);
        return con;
    }

    private static void inicializar(Connection con) throws SQLException {
        try (Statement st = con.createStatement()) {
            st.execute("CREATE TABLE IF NOT EXISTS personas (" +
                "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "nombres VARCHAR(120) NOT NULL, tipo VARCHAR(30) NOT NULL, " +
                "empresa VARCHAR(120), identificador_biometrico VARCHAR(60) NOT NULL UNIQUE, activa BOOLEAN DEFAULT TRUE NOT NULL)");
            st.execute("CREATE TABLE IF NOT EXISTS registros_acceso (" +
                "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, persona VARCHAR(120) NOT NULL, " +
                "tipo_movimiento VARCHAR(20) NOT NULL, resultado VARCHAR(30) NOT NULL, " +
                "detalle VARCHAR(250) NOT NULL, fecha_hora TIMESTAMP NOT NULL)");
        }
    }
}
